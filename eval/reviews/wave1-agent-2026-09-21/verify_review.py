"""Validate review coverage and input hashes; regenerate the verdict index.

This checks bookkeeping, not the scientific correctness of review conclusions.
Run from any directory with Python 3; no dependencies or network are required.
"""

import collections
import hashlib
import json
from pathlib import Path
import re


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    manifest = json.loads((HERE / "manifest.json").read_text())
    assert digest(ROOT / "data/corpus/corpus.json") == manifest["corpus_sha256"], "Corpus changed"
    for name, sha in json.loads((HERE / "context-hashes.json").read_text()).items():
        assert digest(ROOT / name) == sha, f"Reviewed policy/harness changed: {name}"
    expected_files = set(manifest["fixture_sha256"])
    actual_files = {p.name for p in (ROOT / "eval/fixtures-wave1").glob("*.json")}
    assert actual_files == expected_files, "Fixture set changed"
    for name, sha in manifest["fixture_sha256"].items():
        assert digest(ROOT / "eval/fixtures-wave1" / name) == sha, f"Fixture changed: {name}"

    rows = []
    seen = set()
    for number, batch in enumerate(manifest["batches"], 1):
        report = (HERE / f"batch-{number}.md").read_text()
        matches = list(re.finditer(
            r"^## ([a-z][a-z0-9-]+) - (KEEP|EDIT|UNVERIFIABLE|RETIRE)\n(.*?)(?=^## |\Z)",
            report, re.M | re.S,
        ))
        assert len(matches) == len(batch), f"Section count: batch {number}"
        sections = {m[1]: (m[2], m[3]) for m in matches}
        assert set(sections) == set(batch), f"Section IDs: batch {number}"
        for fixture_id in batch:
            assert fixture_id not in seen, f"Duplicate fixture: {fixture_id}"
            seen.add(fixture_id)
            fixture = json.loads((ROOT / "eval/fixtures-wave1" / f"{fixture_id}.json").read_text())
            verdict, section = sections[fixture_id]
            coverage = collections.defaultdict(set)
            for line in section.splitlines():
                turn = re.match(r"- T([12]) ", line)
                if turn:
                    for kind, first, last in re.findall(r"\b(MC|MN)(\d+)(?:-(\d+))?", line):
                        coverage[int(turn[1]), kind].update(range(int(first), int(last or first) + 1))
            conditions = 0
            for turn_number, turn in enumerate(fixture["turns"], 1):
                for kind, key in (("MC", "must_contain"), ("MN", "must_not")):
                    expected = set(range(1, len(turn["rubric"].get(key, [])) + 1))
                    assert coverage[turn_number, kind] == expected, (
                        fixture_id, turn_number, kind, "coverage mismatch",
                        sorted(expected ^ coverage[turn_number, kind]),
                    )
                    conditions += len(expected)
            rows.append(dict(id=fixture_id, batch=number, verdict=verdict,
                             turns=len(fixture["turns"]), conditions=conditions))

    assert seen == {Path(name).stem for name in expected_files}, "Incomplete manifest coverage"
    (HERE / "verdicts.json").write_text(json.dumps(rows, indent=2) + "\n")
    index = ["# Fixture verdict index", "", "Generated by `verify_review.py` from the batch reports.", "",
             "KEEP denotes source validity with stated qualifications; it does not clear shared harness blockers.", "",
             "| Fixture | Verdict | Batch | Conditions |", "|---|---|---|---:|"]
    for row in rows:
        index.append(f"| {row['id']} | {row['verdict']} | [Report](batch-{row['batch']}.md) | {row['conditions']} |")
    (HERE / "INDEX.md").write_text("\n".join(index) + "\n")
    print(json.dumps(dict(fixtures=len(rows), turns=sum(r["turns"] for r in rows),
                          conditions=sum(r["conditions"] for r in rows),
                          verdicts=dict(collections.Counter(r["verdict"] for r in rows)),
                          input_hashes="unchanged", condition_identifier_coverage="complete")))


if __name__ == "__main__":
    main()
